export function callerName(wxid, lang = 'en') {
  let h = 5381
  for (let i = 0; i < wxid.length; i++) h = (((h << 5) + h) ^ wxid.charCodeAt(i)) >>> 0
  const h2 = ((h << 13) ^ h ^ (h >>> 7)) >>> 0
  const [lv, ln] = LANGS[lang] || [V, N]
  return `${lv[h % lv.length]}${lang.startsWith('zh') || lang === 'ja' || lang === 'ko' ? '' : ' '}${ln[h2 % ln.length]}`
}

